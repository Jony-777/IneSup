create table if not exists public.opiniones (
  id bigint generated by default as identity primary key,
  propuesta text not null check (char_length(propuesta) between 10 and 800),
  categoria text not null check (categoria in ('Infraestructura', 'Juventud', 'Educación', 'Participación Cívica')),
  ciudad text not null check (char_length(ciudad) between 2 and 80),
  codigo_postal text not null check (codigo_postal ~ '^\d{5}$'),
  colonia text not null check (char_length(colonia) between 2 and 100),
  seccion text not null check (char_length(seccion) between 1 and 12),
  created_at timestamptz not null default now()
);

create index if not exists opiniones_created_at_idx on public.opiniones (created_at desc);
create index if not exists opiniones_ubicacion_idx on public.opiniones (ciudad, codigo_postal, colonia, seccion);

alter table public.opiniones enable row level security;

revoke all on table public.opiniones from anon, authenticated;
grant select, insert, update, delete on table public.opiniones to service_role;
grant usage, select on sequence public.opiniones_id_seq to service_role;

drop policy if exists "deny public access to opiniones" on public.opiniones;
create policy "deny public access to opiniones"
on public.opiniones
as restrictive
for all
to anon, authenticated
using (false)
with check (false);
